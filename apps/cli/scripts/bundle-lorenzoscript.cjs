// Regenerate with Node + the repository's installed TypeScript. Runtime needs only V8.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../../..');
const source = path.join(root, 'packages/lorenzoscript/src');
const ts = require(process.argv[2] || path.join(root, 'packages/lorenzoscript/node_modules/typescript'));
const names = fs.readdirSync(source).filter(n => n.endsWith('.ts')).sort();
const hash = crypto.createHash('sha256');
const modules = names.map(name => {
  const text = fs.readFileSync(path.join(source, name), 'utf8').replace(/\r\n/g, '\n');
  hash.update(name + '\n' + text);
  const js = ts.transpileModule(text, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText;
  return JSON.stringify('./' + name.slice(0, -3)) + ': function(exports, require) {\n' + js + '\n}';
});
const output = '// Generated by scripts/bundle-lorenzoscript.cjs; source-sha256: ' + hash.digest('hex') + '\n' +
  'var LorenzoScript = (() => {\nconst modules = {' + modules.join(',\n') + '};\n' +
  'const cache = {}; function require(name) { if (!cache[name]) { const exports = {}; cache[name] = exports; modules[name](exports, require); } return cache[name]; }\n' +
  'return require("./index");\n})();\n';
fs.writeFileSync(path.join(root, 'apps/cli/src/lorenzo_cli/lorenzoscript.js'), output);

